type Ctx = { lang: Lang; dir: 'rtl' | 'ltr'; setLang: (l: Lang) => void; toggleLang: () => void; t: (key: string, vars?: Record<string, string | number>) => string };
const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const stored = localStorage.getItem('mda.lang') as Lang | null;
    return stored === 'en' || stored === 'ar' ? stored : 'ar';
  });
  const dir = lang === 'ar' ? 'rtl' : 'ltr';

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
    localStorage.setItem('mda.lang', lang);
  }, [lang, dir]);

  const setLang = useCallback((l: Lang) => setLangState(l), []);
  const t = useCallback((key: string, vars?: Record<string, string | number>) => {
    const entry = DICT[key];
    let text = entry ? entry[lang === 'ar' ? 0 : 1] : key;
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    return text;
  }, [lang]);

  const value = useMemo<Ctx>(() => ({
    lang, dir, setLang, t,
    toggleLang: () => setLangState((l) => (l === 'ar' ? 'en' : 'ar')),
  }), [lang, dir, setLang, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}

export function pickLang<T>(ar: T, en: T, lang: Lang): T {
  return lang === 'ar' ? ar : en;
}
